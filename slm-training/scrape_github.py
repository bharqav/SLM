"""
Phase 1: Collect code comments, docstrings and README prose from top GitHub repos.

Streams each repo's tarball, extracts natural-language records, dedupes, and
appends them to raw_data.txt.

Record format
-------------
raw_data.txt is a UTF-8 text file of *records* separated by a line containing
exactly `<|endoftext|>`. A record is usually one line (a comment) but may span
several (a signature plus its docstring). This deviates from a strictly
line-delimited file so that multi-line docstrings survive as single documents;
preprocess.py appends one <eos> per record.

Usage
-----
    python scrape_github.py --target-tokens 120000000 --min-stars 1000
"""
import argparse
import ast
import hashlib
import io
import json
import os
import re
import subprocess
import sys
import tarfile
import tempfile
import time
import tokenize

import requests

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from slmlog import log, warn, error, human, fmt_dur

HERE = os.path.dirname(os.path.abspath(__file__))
RAW_PATH = os.path.join(HERE, "raw_data.txt")
STATE_PATH = os.path.join(HERE, "scrape_state.json")
STATS_PATH = os.path.join(HERE, "scrape_stats.json")

RECORD_SEP = "<|endoftext|>"
CHARS_PER_TOKEN = 3.6            # empirical for code-comment English
MAX_TARBALL_BYTES = 180 * 1024 * 1024
# Hard ceiling on time spent on any one repository. Without it a stalled
# connection blocks the whole scrape indefinitely.
REPO_DEADLINE_SECONDS = 240
MAX_FILE_BYTES = 1024 * 1024
MIN_RECORD_CHARS = 10
README_CHAR_LIMIT = 5000
API = "https://api.github.com"

# Vendored / generated / minified trees carry no original prose.
SKIP_PATH_RE = re.compile(
    r"(^|/)(node_modules|vendor|third_party|thirdparty|dist|build|out|"
    r"site-packages|bower_components|__pycache__|\.venv|venv|externals|"
    r"fixtures|testdata|test_data|snapshots|__snapshots__|migrations|locale|"
    r"translations|generated|_generated|autogen)(/|$)",
    re.I,
)
SKIP_FILE_RE = re.compile(r"(\.min\.js|\.bundle\.js|-lock\.json|\.map)$", re.I)

# Boilerplate that would otherwise dominate the corpus.
LICENSE_RE = re.compile(
    r"(copyright\s*\(c\)|licensed under the|all rights reserved|"
    r"permission is hereby granted|redistribution and use in source|"
    r"spdx-license-identifier|apache license|gnu general public|"
    r"the software is provided|without warranty of any kind|"
    r"see the license for the specific language)",
    re.I,
)
GENERATED_RE = re.compile(
    r"(do not edit|auto-?generated|automatically generated|generated by|"
    r"code generated by|this file was generated|@generated|eslint-disable|"
    r"prettier-ignore|pylint: disable|istanbul ignore|jshint|tslint:disable)",
    re.I,
)
DECORATION_RE = re.compile(r"^[\s#/*=\-_~+.<>|!]*$")
URL_ONLY_RE = re.compile(r"^\s*(https?://\S+\s*)+$", re.I)

# Lines that read as source code rather than prose. Used to discard records
# where a comment-delimiter regex ran into a string literal and swallowed code.
CODE_LINE_RE = re.compile(
    r"(;\s*$|\{\s*$|^\s*[}\])]|=>|\)\s*\{|"
    r"^\s*(const|let|var|return|import|export|from|function|class|if|for|while|"
    r"switch|case|await|async|def|elif|try|except|raise|yield)\b[^\n]*[;{)\[]|"
    r"^\s*[\w$.]+\s*=[^=]|^\s*@[\w$.]+\()"
)


def looks_like_code(rec):
    """True when most non-empty lines of a record parse as code, not prose."""
    lines = [ln for ln in rec.split("\n") if ln.strip()]
    if not lines:
        return True
    hits = sum(1 for ln in lines if CODE_LINE_RE.search(ln))
    return hits / len(lines) > 0.5

PY_EXT = (".py",)
JS_EXT = (".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx")
README_RE = re.compile(r"(^|/)readme(\.md|\.rst|\.markdown|\.txt|)$", re.I)


# ------------------------------------------------------------------ helpers
def gh_token():
    tok = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if tok:
        return tok.strip()
    try:
        out = subprocess.run(["gh", "auth", "token"], capture_output=True,
                             text=True, timeout=30)
        if out.returncode == 0 and out.stdout.strip():
            return out.stdout.strip()
    except Exception:
        pass
    return None


def clean_text(s):
    """Normalise newlines, drop control characters, trim blank edges."""
    s = s.replace("\r\n", "\n").replace("\r", "\n").replace("\x00", "")
    s = "".join(c for c in s if c in "\n\t" or ord(c) >= 32)
    lines = [ln.rstrip() for ln in s.split("\n")]
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    return "\n".join(lines)


def mostly_ascii(s, threshold=0.90):
    if not s:
        return False
    return sum(1 for c in s if ord(c) < 128) / len(s) >= threshold


def acceptable(rec, kind=""):
    """Quality gate applied to every candidate record.

    `kind` matters: docstring records deliberately carry a signature line, so
    the code-shape rejector only applies to bare comment records.
    """
    if len(rec) < MIN_RECORD_CHARS:
        return False
    if kind.endswith("_comment") and looks_like_code(rec):
        return False
    stripped = rec.strip()
    if not stripped or DECORATION_RE.match(stripped):
        return False
    if URL_ONLY_RE.match(stripped):
        return False
    if LICENSE_RE.search(rec) or GENERATED_RE.search(rec):
        return False
    if not mostly_ascii(rec):
        return False
    letters = sum(1 for c in rec if c.isalpha())
    if letters < 8 or letters / len(rec) < 0.35:
        return False
    return True


def strip_markers(text, kind):
    if kind == "py":
        return re.sub(r"^\s*#+\s?", "", text)
    lines = []
    for ln in text.split("\n"):
        ln = re.sub(r"^\s*/\*+\s?", "", ln)
        ln = re.sub(r"\s*\*+/\s*$", "", ln)
        ln = re.sub(r"^\s*\*\s?", "", ln)
        ln = re.sub(r"^\s*//+\s?", "", ln)
        lines.append(ln.rstrip())
    return "\n".join(lines)


# --------------------------------------------------------------- extractors
def py_signature(node):
    """Reconstruct a readable signature line from an AST node."""
    try:
        if isinstance(node, ast.ClassDef):
            bases = ", ".join(ast.unparse(b) for b in node.bases)
            return "class {}({}):".format(node.name, bases) if bases \
                else "class {}:".format(node.name)
        kw = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
        args = ast.unparse(node.args)
        ret = " -> {}".format(ast.unparse(node.returns)) if node.returns else ""
        return "{} {}({}){}:".format(kw, node.name, args, ret)
    except Exception:
        return None


def indent_doc(doc):
    if "\n" not in doc:
        return '    """{}"""'.format(doc)
    body = "\n".join("    " + ln if ln.strip() else "" for ln in doc.split("\n"))
    return '    """\n{}\n    """'.format(body)


def extract_python(src):
    """Return (kind, record) pairs: signature+docstring blocks and comments."""
    out = []
    try:
        tree = ast.parse(src)
    except (SyntaxError, ValueError, RecursionError, MemoryError):
        tree = None

    if tree is not None:
        targets = (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)
        for node in ast.walk(tree):
            if not isinstance(node, targets):
                continue
            try:
                doc = ast.get_docstring(node, clean=True)
            except Exception:
                doc = None
            if not doc:
                continue
            doc = clean_text(doc)
            if not doc:
                continue
            if isinstance(node, ast.Module):
                out.append(("py_docstring", doc))
                continue
            sig = py_signature(node)
            if sig and len(sig) < 400:
                out.append(("py_docstring", sig + "\n" + indent_doc(doc)))
            else:
                out.append(("py_docstring", doc))

    # Comments via tokenize; consecutive comment lines become one record.
    try:
        block, prev_row = [], None
        for tok in tokenize.generate_tokens(io.StringIO(src).readline):
            if tok.type != tokenize.COMMENT:
                continue
            row = tok.start[0]
            if prev_row is not None and row != prev_row + 1 and block:
                out.append(("py_comment", clean_text("\n".join(block))))
                block = []
            block.append(strip_markers(tok.string, "py"))
            prev_row = row
        if block:
            out.append(("py_comment", clean_text("\n".join(block))))
    except Exception:
        pass
    return out


JS_BLOCK_RE = re.compile(r"^[ 	]*/\*\*?[\s\S]*?\*/", re.M)
JS_LINE_RE = re.compile(r"^[ \t]*//(.*)$", re.M)
JS_DECL_RE = re.compile(
    r"^[ \t]*(export\s+)?(default\s+)?(async\s+)?"
    r"(function\s*\*?\s*[\w$]*\s*\([^)]{0,300}\)|"
    r"class\s+[\w$]+[^{]{0,120}|"
    r"(const|let|var)\s+[\w$]+\s*=\s*(async\s*)?(\([^)]{0,300}\)|[\w$]+)\s*=>|"
    r"[\w$]+\s*\([^)]{0,300}\)\s*\{)"
)


def extract_javascript(src):
    out = []
    # JSDoc blocks paired with the declaration that follows them.
    for m in JS_BLOCK_RE.finditer(src):
        body = clean_text(strip_markers(m.group(0), "js"))
        if not body:
            continue
        decl = None
        for ln in src[m.end():m.end() + 500].split("\n"):
            if not ln.strip():
                continue
            if JS_DECL_RE.match(ln):
                decl = ln.strip().rstrip("{").strip()
            break
        if decl and len(decl) < 300:
            block = "/**\n" + "\n".join(" * " + l for l in body.split("\n")) + "\n */"
            out.append(("js_docstring", block + "\n" + decl))
        else:
            out.append(("js_docstring", body))

    # Line comments, consecutive runs grouped. Block comments masked out first
    # so their inner text is not re-harvested.
    masked = JS_BLOCK_RE.sub(lambda m: "\n" * m.group(0).count("\n"), src)
    block, prev_row = [], None
    for m in JS_LINE_RE.finditer(masked):
        row = masked.count("\n", 0, m.start())
        if prev_row is not None and row != prev_row + 1 and block:
            out.append(("js_comment", clean_text("\n".join(block))))
            block = []
        block.append(m.group(1).strip())
        prev_row = row
    if block:
        out.append(("js_comment", clean_text("\n".join(block))))
    return out


def extract_readme(src):
    text = clean_text(src)[:README_CHAR_LIMIT]
    lines = [ln for ln in text.split("\n")
             if not re.match(r"^\s*(\[!\[|<img|<p align|<div|<a href|<br|</)", ln, re.I)]
    text = clean_text("\n".join(lines))
    return [("readme", text)] if text else []


# ------------------------------------------------------------- GitHub client
class GitHub:
    def __init__(self, token):
        self.s = requests.Session()
        headers = {"Accept": "application/vnd.github+json",
                   "User-Agent": "slm-training-scraper"}
        if token:
            headers["Authorization"] = "Bearer " + token
        self.s.headers.update(headers)

        # Archives are fetched straight from codeload on a separate,
        # unauthenticated session. Going through /repos/{r}/tarball redirects
        # here anyway, but forwarding the API credentials to codeload trips its
        # secondary rate limiter almost immediately.
        self.dl = requests.Session()
        self.dl.headers.update({"User-Agent": "slm-training-scraper",
                                "Accept": "application/x-gzip"})

    def _sleep_for_rate_limit(self, resp):
        retry_after = resp.headers.get("Retry-After")
        if retry_after:
            wait = min(int(retry_after), 300)
        else:
            reset = resp.headers.get("X-RateLimit-Reset")
            wait = 60
            if reset:
                wait = max(5, min(int(reset) - int(time.time()) + 5, 900))
        warn("Rate limited (HTTP {}). Sleeping {}s.".format(resp.status_code, wait))
        time.sleep(wait)

    def get(self, url, params=None, retries=3, stream=False, timeout=30):
        for attempt in range(retries + 1):
            try:
                r = self.s.get(url, params=params, stream=stream, timeout=timeout)
            except requests.RequestException as e:
                if attempt == retries:
                    raise
                warn("Request error ({}); retry {}/{}".format(e, attempt + 1, retries))
                time.sleep(5 * (attempt + 1))
                continue
            if r.status_code in (403, 429):
                remaining = r.headers.get("X-RateLimit-Remaining")
                if remaining == "0" or r.status_code == 429:
                    self._sleep_for_rate_limit(r)
                    continue
            if r.status_code >= 500:
                if attempt == retries:
                    return r
                warn("HTTP {} from GitHub; retry {}/{}".format(
                    r.status_code, attempt + 1, retries))
                time.sleep(5 * (attempt + 1))
                continue
            return r
        return r

    def search_repos(self, language, min_stars, max_repos):
        """Top repos by stars, excluding forks and archived."""
        found, page = [], 1
        query = "language:{} stars:>={} fork:false archived:false".format(
            language, min_stars)
        while len(found) < max_repos and page <= 10:
            r = self.get(API + "/search/repositories",
                         params={"q": query, "sort": "stars", "order": "desc",
                                 "per_page": 100, "page": page})
            if r.status_code != 200:
                warn("Search failed for {} page {}: HTTP {}".format(
                    language, page, r.status_code))
                break
            items = r.json().get("items", [])
            if not items:
                break
            for it in items:
                if it.get("fork") or it.get("archived"):
                    continue
                found.append({"full_name": it["full_name"],
                              "stars": it.get("stargazers_count", 0),
                              "default_branch": it.get("default_branch", "main"),
                              "language": language})
            page += 1
            time.sleep(2)  # search API is 30 req/min
        return found[:max_repos]


# ------------------------------------------------------------ repo processing
def fetch_tarball(gh, repo, retries=3):
    """Open a streaming response for the repo archive from codeload."""
    url = "https://codeload.github.com/{}/tar.gz/refs/heads/{}".format(
        repo["full_name"], repo["default_branch"])
    for attempt in range(retries + 1):
        try:
            r = gh.dl.get(url, stream=True, timeout=(15, 30))
        except requests.RequestException as e:
            if attempt == retries:
                raise RuntimeError("download error: {}".format(e))
            time.sleep(3 * (attempt + 1))
            continue
        if r.status_code == 200:
            return r
        r.close()
        if r.status_code in (403, 429):
            wait = min(int(r.headers.get("Retry-After", 20)), 120)
            warn("codeload throttled ({}); backing off {}s".format(
                r.status_code, wait))
            time.sleep(wait)
            continue
        if r.status_code == 404:
            raise RuntimeError("archive 404 (branch {})".format(
                repo["default_branch"]))
        if attempt == retries:
            raise RuntimeError("archive HTTP {}".format(r.status_code))
        time.sleep(3 * (attempt + 1))
    raise RuntimeError("archive unavailable after retries")


def download_tarball(gh, repo, dest):
    """Download the archive to `dest` under a size cap and a wall-clock deadline.

    Earlier versions handed `response.raw` straight to tarfile. That streams
    with no byte cap, and a stalled connection hangs forever because the socket
    timeout does not propagate through the raw file object -- one dead peer
    froze the whole scrape indefinitely. Pulling through iter_content keeps the
    read timeout live and lets us bound both size and total time.
    """
    r = fetch_tarball(gh, repo)
    size = r.headers.get("Content-Length")
    if size and int(size) > MAX_TARBALL_BYTES:
        r.close()
        raise RuntimeError("tarball too large ({} MB)".format(int(size) >> 20))

    deadline = time.time() + REPO_DEADLINE_SECONDS
    written = 0
    try:
        with open(dest, "wb") as fh:
            for chunk in r.iter_content(chunk_size=256 * 1024):
                if not chunk:
                    continue
                written += len(chunk)
                if written > MAX_TARBALL_BYTES:
                    raise RuntimeError("tarball exceeded {} MB cap".format(
                        MAX_TARBALL_BYTES >> 20))
                if time.time() > deadline:
                    raise RuntimeError("download exceeded {}s deadline".format(
                        REPO_DEADLINE_SECONDS))
                fh.write(chunk)
    finally:
        r.close()
    return written


def iter_repo_files(gh, repo):
    """Download the repo archive, yielding (path, text) for files of interest."""
    fd, tmp = tempfile.mkstemp(suffix=".tar.gz", prefix="slm_repo_", dir=HERE)
    os.close(fd)
    try:
        download_tarball(gh, repo, tmp)
        with tarfile.open(tmp, mode="r:gz") as tar:
            for member in tar:
                if not member.isfile() or member.size > MAX_FILE_BYTES:
                    continue
                # Strip the "<owner>-<repo>-<sha>/" prefix GitHub adds.
                path = member.name.split("/", 1)[-1]
                low = path.lower()
                is_readme = bool(README_RE.search(low))
                if not (low.endswith(PY_EXT) or low.endswith(JS_EXT) or is_readme):
                    continue
                if SKIP_PATH_RE.search(low) or SKIP_FILE_RE.search(low):
                    continue
                try:
                    fh = tar.extractfile(member)
                    if fh is None:
                        continue
                    raw = fh.read()
                except Exception:
                    continue
                try:
                    text = raw.decode("utf-8")
                except UnicodeDecodeError:
                    continue
                if "\x00" in text[:4096]:
                    continue
                yield path, text
    finally:
        try:
            os.remove(tmp)
        except OSError:
            pass


def records_for(path, text):
    low = path.lower()
    if README_RE.search(low):
        return extract_readme(text)
    if low.endswith(PY_EXT):
        return extract_python(text)
    if low.endswith(JS_EXT):
        return extract_javascript(text)
    return []


# ------------------------------------------------------------------- driver
def load_state():
    if os.path.exists(STATE_PATH):
        try:
            with open(STATE_PATH, encoding="utf-8") as fh:
                return json.load(fh)
        except Exception:
            warn("scrape_state.json unreadable; starting fresh.")
    return {"done_repos": [], "chars": 0, "records": 0,
            "by_kind": {}, "repos_ok": 0, "repos_failed": 0}


def save_state(state):
    tmp = STATE_PATH + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(state, fh, indent=2)
    os.replace(tmp, STATE_PATH)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--target-tokens", type=int, default=120_000_000)
    ap.add_argument("--min-stars", type=int, default=1000)
    ap.add_argument("--max-repos-per-lang", type=int, default=600)
    ap.add_argument("--languages", default="python,javascript")
    ap.add_argument("--fresh", action="store_true",
                    help="ignore existing state and truncate raw_data.txt")
    args = ap.parse_args()

    token = gh_token()
    if not token:
        error("No GitHub token. Set GITHUB_TOKEN or run `gh auth login`.")
        return 1

    if args.fresh:
        for p in (RAW_PATH, STATE_PATH):
            if os.path.exists(p):
                os.remove(p)

    state = load_state()
    done = set(state["done_repos"])
    seen_hashes = set()

    # Rebuild the dedupe set from an existing corpus so a resumed run does not
    # reintroduce duplicates.
    if done and os.path.exists(RAW_PATH):
        log("Resuming: rebuilding dedupe index from raw_data.txt ...")
        with open(RAW_PATH, encoding="utf-8") as fh:
            buf = []
            for line in fh:
                if line.rstrip("\n") == RECORD_SEP:
                    rec = "\n".join(buf)
                    seen_hashes.add(hashlib.blake2b(
                        rec.encode("utf-8"), digest_size=16).digest())
                    buf = []
                else:
                    buf.append(line.rstrip("\n"))
        log("Dedupe index holds {} records.".format(len(seen_hashes)))

    gh = GitHub(token)
    log("Phase 1: Data Scraping Started")
    log("Target: {} tokens | min stars: {} | max repos/lang: {}".format(
        human(args.target_tokens), args.min_stars, args.max_repos_per_lang))

    repos = []
    for lang in [l.strip() for l in args.languages.split(",") if l.strip()]:
        found = gh.search_repos(lang, args.min_stars, args.max_repos_per_lang)
        log("Discovered {} {} repos (>= {} stars)".format(
            len(found), lang, args.min_stars))
        repos.extend(found)

    # Interleave languages so an early stop still yields a balanced corpus.
    by_lang = {}
    for r in repos:
        by_lang.setdefault(r["language"], []).append(r)
    interleaved, idx = [], 0
    while any(idx < len(v) for v in by_lang.values()):
        for lang in by_lang:
            if idx < len(by_lang[lang]):
                interleaved.append(by_lang[lang][idx])
        idx += 1
    repos = interleaved
    log("Repo queue: {} repos total ({} already done)".format(len(repos), len(done)))

    target_chars = int(args.target_tokens * CHARS_PER_TOKEN)
    chars = state["chars"]
    records = state["records"]
    by_kind = state["by_kind"]
    started = time.time()
    processed_this_run = 0

    out = open(RAW_PATH, "a", encoding="utf-8", newline="\n")
    try:
        for i, repo in enumerate(repos, 1):
            if chars >= target_chars:
                log("Target token count reached; stopping repo loop.")
                break
            name = repo["full_name"]
            if name in done:
                continue

            t0 = time.time()
            repo_records, repo_chars, files_seen = [], 0, 0
            try:
                for path, text in iter_repo_files(gh, repo):
                    files_seen += 1
                    try:
                        for kind, rec in records_for(path, text):
                            rec = clean_text(rec)
                            if not acceptable(rec, kind):
                                continue
                            h = hashlib.blake2b(rec.encode("utf-8"),
                                                digest_size=16).digest()
                            if h in seen_hashes:
                                continue
                            seen_hashes.add(h)
                            repo_records.append((kind, rec))
                            repo_chars += len(rec)
                    except Exception as e:
                        warn("extract failed {}:{} ({})".format(name, path, e))
            except Exception as e:
                state["repos_failed"] += 1
                done.add(name)
                warn("[{}/{}] {} skipped: {}".format(i, len(repos), name, e))
                state["done_repos"] = sorted(done)
                save_state(state)
                continue

            for kind, rec in repo_records:
                out.write(rec)
                out.write("\n")
                out.write(RECORD_SEP)
                out.write("\n")
                by_kind[kind] = by_kind.get(kind, 0) + 1
            out.flush()

            chars += repo_chars
            records += len(repo_records)
            done.add(name)
            state.update({"done_repos": sorted(done), "chars": chars,
                          "records": records, "by_kind": by_kind,
                          "repos_ok": state["repos_ok"] + 1})
            processed_this_run += 1

            est_tokens = chars / CHARS_PER_TOKEN
            frac = min(1.0, chars / target_chars) if target_chars else 1.0
            elapsed = time.time() - started
            eta = (elapsed / frac - elapsed) if frac > 0.001 else 0
            log("[{}/{}] {} ({} stars, {}) - {} files, {} records, "
                "{} tok | total {} tok ({:.1f}%) | {:.0f}s | ETA {}".format(
                    i, len(repos), name, human(repo["stars"]), repo["language"],
                    files_seen, len(repo_records),
                    human(repo_chars / CHARS_PER_TOKEN), human(est_tokens),
                    frac * 100, time.time() - t0, fmt_dur(eta)))

            if processed_this_run % 10 == 0:
                save_state(state)
                log("  -> checkpoint: {} repos ok, {} failed, {} records, {} est tokens"
                    .format(state["repos_ok"], state["repos_failed"],
                            records, human(est_tokens)))
    except KeyboardInterrupt:
        warn("Interrupted; saving state.")
    finally:
        out.close()
        save_state(state)

    est_tokens = chars / CHARS_PER_TOKEN
    stats = {
        "repos_ok": state["repos_ok"],
        "repos_failed": state["repos_failed"],
        "records": records,
        "chars": chars,
        "estimated_tokens": int(est_tokens),
        "by_kind": by_kind,
        "raw_bytes": os.path.getsize(RAW_PATH) if os.path.exists(RAW_PATH) else 0,
        "elapsed_seconds": round(time.time() - started, 1),
    }
    with open(STATS_PATH, "w", encoding="utf-8") as fh:
        json.dump(stats, fh, indent=2)

    log("Phase 1: Complete ({} repos ok, {} failed, {} records, ~{} tokens, {} MB)"
        .format(stats["repos_ok"], stats["repos_failed"], records,
                human(est_tokens), stats["raw_bytes"] >> 20))
    log("Record kinds: {}".format(json.dumps(by_kind)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
